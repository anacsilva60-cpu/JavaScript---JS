// Atribuindo Variável 
// 01 - Const

const nome = "Aninha"; // --------> Usado para algo constante que só altera o valor
console.log(nome); // ----> Exibir

// 02 - Let

let nome_gato = "Felix"; // -------> Usado para algo que altera com maior frequência
console.log(nome_gato);

// Alterando a variável 

let nome_novo = "Ana";
nome_novo = "Carlos";
console.log(nome_novo);

// ----------- Variavel com Números --------------

const idade = 16;
idade = 18;
console.log(idade);

let idade_nova = 16;
idade_nova = 18;
console.log(idade_nova);